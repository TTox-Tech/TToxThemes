def render(ctx) -> dict:
    d = f"apps/firefox/{ctx.slug}/"
    sub = {"title": ctx.title, "pref": PREF, "vars": _vars(ctx)}
    content_sub = dict(sub, vars="\n".join("  " + ln for ln in _vars(ctx).split("\n")))
    return {
        d + "userChrome.css": CHROME % sub,
        d + "userContent.css": CONTENT % content_sub,
        "apps/firefox/user.js": USERJS % sub,
    }
