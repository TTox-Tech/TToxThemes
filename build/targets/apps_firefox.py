def _vars(ctx) -> str:
    p, t = ctx.p, ctx.tokens
    v = {
        "bg": p["bg"], "surface": p["surface"], "raised": p["raised"], "line": p["line"], "muted": p["muted"],
        "fg": p["fg"], "fg-hi": p["fg_hi"], "accent": p["accent"], "accent2": p["accent2"],
        "accent-text": p["accent_text"], "err": p["err"],
        "side": lib.darken(p["bg"], SIDEBAR_DARKEN),
        "select": ctx.rgba(p["accent"], t["wash"]["select_alpha"]),
        "hover": ctx.rgba(p["fg"], t["wash"]["hover_alpha"]),
        "hairline": ctx.rgba(p["fg"], t["border"]["hairline_alpha"]),
        "sep": ctx.rgba(p["line"], t["border"]["sep_alpha"]),
        "scroll": ctx.rgba(p["muted"], 0.50),
        "r-control": f"{t['radius']['control']}px", "r-wash": f"{t['radius']['wash']}px",
        "r-popup": f"{t['radius']['popup']}px", "r-menu": f"{t['radius']['menu']}px",
        "font-ui": f"\"{t['font']['ui']}\", \"{t['font']['ui_fallback']}\", sans-serif",
        "font-mono": f"\"{t['font']['mono']}\", \"{t['font']['mono_fallback']}\", monospace",
    }
    return "\n".join(f"  --ttox-{k}: {val};" for k, val in sorted(v.items()))


