"""Plasma colour scheme: dist/kde/color-schemes/ttox-<variant>/TTox<Variant>.colors

Installed to ~/.local/share/color-schemes/ and applied with plasma-apply-colorscheme.
Mode-independent (transparency comes from Kvantum/KWin, not the scheme).
"""
from __future__ import annotations
import os, sys
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import kde_common as K  # noqa: E402
import lib  # noqa: E402

NAME = "kde_colorscheme"
PACK = "kde"


def file_name(ctx) -> str:
    return "TTox" + K.cap(ctx.name)


def group(p: dict, bg: str, alt: str, fg: str, inactive: str, d: dict, focus: str = None) -> list:
    c = lib.rgb_csv
    return [
        ("BackgroundAlternate", c(alt)), ("BackgroundNormal", c(bg)),
        ("DecorationFocus", c(focus or p["accent"])), ("DecorationHover", c(p["accent_text"])),
        ("ForegroundActive", c(p["accent_text"])), ("ForegroundInactive", c(inactive)),
        ("ForegroundLink", c(p["accent_text"])), ("ForegroundNegative", c(p["err"])),
        ("ForegroundNeutral", c(p["warn"])), ("ForegroundNormal", c(fg)),
        ("ForegroundPositive", c(p["ok"])), ("ForegroundVisited", c(d["visited"])),
    ]


def render(ctx):
    p, t = ctx.p, ctx.tokens
    d = K.derived(p, t)
    c = lib.rgb_csv
    sections = [
        ("ColorEffects:Disabled", [("Color", c(p["surface"])), ("ColorAmount", "0"), ("ColorEffect", "0"),
                                   ("ContrastAmount", "0.65"), ("ContrastEffect", "1"),
                                   ("IntensityAmount", "0.1"), ("IntensityEffect", "2")]),
        ("ColorEffects:Inactive", [("ChangeSelectionColor", "true"), ("Color", c(p["bg"])),
                                   ("ColorAmount", "0.025"), ("ColorEffect", "2"), ("ContrastAmount", "0.1"),
                                   ("ContrastEffect", "2"), ("Enable", "false"), ("IntensityAmount", "0"),
                                   ("IntensityEffect", "0")]),
        ("Colors:Button", group(p, p["raised"], d["hover"], p["fg"], p["muted"], d)),
        ("Colors:Complementary", group(p, p["bg"], p["surface"], p["fg"], p["muted"], d)),
        ("Colors:Header", group(p, p["surface"], p["raised"], p["fg"], p["muted"], d)),
        ("Colors:Header[Inactive]", group(p, p["surface"], p["raised"], p["muted"], p["muted"], d)),
        ("Colors:Selection", group(p, d["wash"], d["wash_inactive"], p["fg_hi"], p["fg"], d)),
        ("Colors:Tooltip", group(p, p["raised"], p["surface"], p["fg"], p["muted"], d)),
        ("Colors:View", group(p, d["view"], p["surface"], p["fg"], p["muted"], d)),
        ("Colors:Window", group(p, p["surface"], p["raised"], p["fg"], p["muted"], d)),
        ("General", [("ColorScheme", file_name(ctx)), ("Name", p["title"]), ("accentActiveTitlebar", "false"),
                     ("accentInactiveTitlebar", "false"), ("shadeSortColumn", "true")]),
        ("KDE", [("contrast", "4"), ("widgetStyle", "kvantum")]),
        ("WM", [("activeBackground", c(p["surface"])), ("activeBlend", c(p["accent_text"])),
                ("activeForeground", c(p["fg"])), ("inactiveBackground", c(p["surface"])),
                ("inactiveBlend", c(p["muted"])), ("inactiveForeground", c(p["muted"]))]),
    ]
    text = K.ini(sections, header=f"{p['title']} Plasma colour scheme. Generated by TToxThemes, do not edit.")
    return {f"kde/color-schemes/{K.scheme_name(ctx.name)}/{file_name(ctx)}.colors": text}
