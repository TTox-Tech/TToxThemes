"""Konsole colour scheme + profile per variant x mode.

dist/kde/konsole/ttox-<variant>-<mode>.colorscheme   -> ~/.local/share/konsole/
dist/kde/konsole/ttox-<variant>-<mode>.profile       -> ~/.local/share/konsole/
konsolerc keys (menubar, tab bar) are written by scripts/apply_kde.sh with kwriteconfig.
"""
from __future__ import annotations
import os, sys
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import kde_common as K  # noqa: E402
import lib  # noqa: E402

NAME = "kde_konsole"
PACK = "kde"


def colorscheme(ctx, mode: str, m: dict) -> str:
    p = ctx.p
    c = lib.rgb_csv
    term = p["term"]
    sec = []

    def entry(name: str, col: str):
        sec.append((name, [("Color", c(col))]))

    entry("Background", p["bg"])
    entry("BackgroundFaint", p["bg"])
    entry("BackgroundIntense", p["bg"])
    for i in range(8):
        entry(f"Color{i}", term[i])
        entry(f"Color{i}Faint", lib.mix(term[i], p["bg"], 0.35))
        entry(f"Color{i}Intense", term[i + 8])
    entry("Foreground", p["fg"])
    entry("ForegroundFaint", p["muted"])
    # bold is not bright: intense foreground stays the normal text colour
    entry("ForegroundIntense", p["fg"])
    sec.append(("General", [("Anchor", "0.5,0.5"), ("Blur", m["blur_term"] > 0), ("ColorRandomization", False),
                            ("Description", f"{p['title']} ({mode})"), ("FillStyle", "Tile"),
                            ("Opacity", "%.2f" % m["term"]), ("Wallpaper", ""), ("WallpaperFlipType", "NoFlip"),
                            ("WallpaperOpacity", "1")]))
    return K.ini(sec, header=f"{p['title']} / {mode} Konsole colours. Generated by TToxThemes, do not edit.")


def profile(ctx, mode: str, m: dict) -> str:
    p, t = ctx.p, ctx.tokens
    f = t["font"]
    sec = [
        ("Appearance", [("AntiAliasFonts", True), ("BoldIntense", False),
                        ("ColorScheme", K.konsole_name(ctx.name, mode)),
                        ("Font", K.qfont(f["mono"], t["term"]["font_pt"], mono=True)),
                        ("UseFontLineChararacters", True)]),
        ("Cursor Options", [("CursorShape", "0"), ("CustomCursorColor", lib.rgb_csv(p["fg"])),
                            ("CustomCursorTextColor", lib.rgb_csv(p["bg"])), ("UseCustomCursorColor", True)]),
        ("General", [("Name", f"{p['title']} ({mode})"), ("Parent", "FALLBACK/"),
                     ("ShowTerminalSizeHint", False), ("TerminalCenter", False),
                     ("TerminalMargin", str(t["term"]["padding"]))]),
        ("Interaction Options", [("TrimLeadingSpacesInSelectedText", True),
                                 ("TrimTrailingSpacesInSelectedText", True)]),
        ("Scrolling", [("HistoryMode", "1"), ("HistorySize", "10000"), ("ScrollBarPosition", "2")]),
        ("Terminal Features", [("BlinkingCursorEnabled", False), ("UrlHintsModifiers", "0")]),
    ]
    return K.ini(sec, header=f"{p['title']} / {mode} Konsole profile. Generated by TToxThemes, do not edit.")


def render(ctx):
    out = {}
    for mode, m in K.modes(ctx):
        n = K.konsole_name(ctx.name, mode)
        out[f"kde/konsole/{n}.colorscheme"] = colorscheme(ctx, mode, m)
        out[f"kde/konsole/{n}.profile"] = profile(ctx, mode, m)
    return out
